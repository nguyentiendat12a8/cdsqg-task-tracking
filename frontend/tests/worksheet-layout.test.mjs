import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fitPresentationRows } from '../src/utils/worksheetLayout.js';
const XLSX = createRequire(import.meta.url)('xlsx-js-style');
const ws = XLSX.utils.aoa_to_sheet([['Tiêu đề dài'], ['Đơn vị báo cáo'], ['HƯỚNG DẪN: Điền số'], ['Tổng', 0], ['STT','Mã','Tên','Giá trị'], [1,'MT-23','Tên dài',20], ['Không có dữ liệu']]);
ws['!cols'] = Array.from({length:4}, () => ({wch:20}));
const options = {numCols:4,headerRowIndex:4};
fitPresentationRows(ws, options, XLSX);
assert.deepEqual(ws['!merges'].map(XLSX.utils.encode_range), ['A1:D1','A2:D2','A3:D3','A4:C4','A7:D7']);
assert.equal(ws.D4.v, 0);
assert.equal(ws.B6.v, 'MT-23'); assert.equal(ws.D6.v, 20);
assert.ok(ws['!rows'][2].hpt >= 24);
const before = JSON.stringify(ws); fitPresentationRows(ws, options, XLSX); assert.equal(JSON.stringify(ws), before);
const complex = XLSX.utils.aoa_to_sheet([['Title'],['Subtitle'],['Label', 'Value'],['STT','Mã','Tên','Value']]);
complex['!merges']=[{s:{r:2,c:2},e:{r:3,c:2}}];
fitPresentationRows(complex,{numCols:4,headerRowIndex:3},XLSX);
assert.equal(complex.B3.v,'Value');
assert.equal(complex['!merges'].filter(m=>m.s.r===2).length,1);
console.log('Worksheet presentation merging: passed');
