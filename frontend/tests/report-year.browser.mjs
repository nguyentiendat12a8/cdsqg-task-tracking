    let data = {};
    if (url.pathname==='/api/agencies') data=[agency];
    else if (url.pathname==='/api/dashboard/metrics') data={totalGoals:count,createdMetrics:{totalGoals:count,goalsSpecific:count,goalStatusSummary:summary},goalStatusSummary:summary,ministriesPerformance:[{...agency,agencyId:agency.id,totalGoals:count,totalItems:count,goalNotStarted:count,notStarted:count}],provincesPerformance:[],othersPerformance:[]};
